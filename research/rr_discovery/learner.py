"""Sequence Scout: CPU-fit symbolic partition hypotheses, then exact held-out tests.

Research demonstration ONLY: labels are modern synthetic mathematical counts.
This is a real finite parameter search, not neural training, a new theorem,
historical khipu decipherment, or qualification of any existing SZL model.

Model: unrestricted partition product with modulus m and nonzero residue
classes R. A fixed, finite, declared hypothesis family is fit against
coefficients 0..32 generated by an independent gap-partition recurrence.
The evaluator is deliberately separate and touches n=33..128 only AFTER
the model is selected, with a fixed negative baseline and tamper control.
"""
from __future__ import annotations

import argparse
import hashlib
import itertools
import json
from functools import lru_cache
from pathlib import Path

SCHEMA = "szl.khipu.sequence-scout/v1"
MODEL_SCHEMA = "szl.khipu.modular-partition-hypothesis/v1"
TRAIN_MAX = 32
EVAL_START = 33
EVAL_END = 128
MAX_MODULUS = 12
MAX_RESIDUE_COUNT = 4
DOMAIN = b"szl.khipu.sequence-scout/v1\x00"
CASES = {"RR1": 1, "RR2": 2}


class EvidenceHold(ValueError):
    """Incorrect source, invalid input or insufficient evidence."""


def canonical(payload: object) -> bytes:
    return json.dumps(
        payload, sort_keys=True, separators=(",", ":"),
        ensure_ascii=True, allow_nan=False,
    ).encode("ascii")


@lru_cache(maxsize=None)
def _gap(n: int, smallest: int) -> int:
    if n == 0:
        return 1
    if n < smallest:
        return 0
    return _gap(n, smallest + 1) + _gap(n - smallest, smallest + 2)


def reference_coefficients(case: str, end: int) -> tuple[int, ...]:
    if case not in CASES or type(end) is not int or not 0 <= end <= EVAL_END:
        raise EvidenceHold("REFERENCE_INPUT_INVALID")
    return tuple(_gap(n, CASES[case]) for n in range(end + 1))


def product_coefficients(modulus: int, residues: tuple[int, ...], end: int) -> tuple[int, ...]:
    if (
        type(modulus) is not int
        or not 2 <= modulus <= MAX_MODULUS
        or type(residues) is not tuple
        or not 1 <= len(residues) <= MAX_RESIDUE_COUNT
        or any(type(v) is not int or not 1 <= v < modulus for v in residues)
        or tuple(sorted(set(residues))) != residues
        or type(end) is not int
        or not 0 <= end <= EVAL_END
    ):
        raise EvidenceHold("PRODUCT_INPUT_INVALID")
    result = [1] + [0] * end
    for part in range(1, end + 1):
        if part % modulus in residues:
            for n in range(part, end + 1):
                result[n] += result[n - part]
    return tuple(result)


def fit(train: tuple[int, ...]) -> dict:
    """Fit on supplied training coefficients ONLY; no access to held-out rows."""
    if (
        type(train) is not tuple
        or len(train) != TRAIN_MAX + 1
        or any(type(v) is not int or not 0 <= v < 10**12 for v in train)
        or train[0] != 1
    ):
        raise EvidenceHold("TRAINING_DATA_INVALID")
    matched = []
    tested = 0
    for modulus in range(2, MAX_MODULUS + 1):
        for n_classes in range(1, min(MAX_RESIDUE_COUNT, modulus - 1) + 1):
            for residues in itertools.combinations(range(1, modulus), n_classes):
                tested += 1
                if product_coefficients(modulus, residues, TRAIN_MAX) == train:
                    matched.append((modulus, len(residues), residues))
    common = {
        "schema": MODEL_SCHEMA,
        "train_rows": len(train),
        "train_end": TRAIN_MAX,
        "train_coefficients_sha256": hashlib.sha256(canonical(train)).hexdigest(),
        "candidate_hypotheses_tested": tested,
        "candidate_matches": len(matched),
        "objective": "exact training coefficient agreement; minimum modulus, then shortest residue list",
        "proof_of_infinite_identity": False,
        "interpretation": "MODERN_SYNTHETIC_MATHEMATICS",
    }
    if not matched:
        return {**common, "status": "HOLD_NO_CANDIDATE", "model": None}
    matched.sort(key=lambda x: (x[0], x[1], x[2]))
    leader = matched[0]
    if len(matched) > 1 and matched[1][:2] == leader[:2]:
        return {**common, "status": "HOLD_AMBIGUOUS_MODEL", "model": None}
    model = {"modulus": leader[0], "residues": list(leader[2])}
    return {
        **common,
        "status": "TRAINING_FIT_EXACT",
        "model": model,
        "model_sha256": hashlib.sha256(DOMAIN + canonical(model)).hexdigest(),
    }


def evaluate(case: str, trained: dict) -> dict:
    """Held-out evaluation. Called only after fit() has returned a frozen model."""
    if case not in CASES:
        raise EvidenceHold("EVALUATION_CASE_INVALID")
    if trained.get("status") != "TRAINING_FIT_EXACT" or trained.get("model") is None:
        return {"status": "NOT_EVALUATED", "reason": "NO_FITTED_MODEL"}
    model = trained["model"]
    if trained.get("model_sha256") != hashlib.sha256(DOMAIN + canonical(model)).hexdigest():
        raise EvidenceHold("TRAINED_MODEL_DIGEST_MISMATCH")
    observed = reference_coefficients(case, EVAL_END)
    predicted = product_coefficients(
        model["modulus"], tuple(model["residues"]), EVAL_END,
    )
    evaluation_indices = list(range(EVAL_START, EVAL_END + 1))
    correct = sum(predicted[n] == observed[n] for n in evaluation_indices)
    first_failure = next(
        (n for n in evaluation_indices if predicted[n] != observed[n]), None
    )
    # A frozen baseline without model parameters: repeat the last training count.
    baseline_value = observed[TRAIN_MAX]
    baseline_correct = sum(observed[n] == baseline_value for n in evaluation_indices)
    return {
        "status": "FINITE_HOLDOUT_MATCH" if correct == len(evaluation_indices) else "FINITE_HOLDOUT_MISMATCH",
        "test_range": [EVAL_START, EVAL_END],
        "test_rows": len(evaluation_indices),
        "exact_matches": correct,
        "first_mismatch_degree": first_failure,
        "training_last_value_baseline_exact_matches": baseline_correct,
        "target_dataset": "independent gap-partition recurrence",
        "model_dataset": "modular-partition product recurrence",
        "test_coefficients_sha256": hashlib.sha256(
            canonical(observed[EVAL_START:])
        ).hexdigest(),
        "predictions_sha256": hashlib.sha256(
            canonical(predicted[EVAL_START:])
        ).hexdigest(),
        "no_heldout_data_used_by_fitter": True,
        "out_of_distribution_archaeology": "NOT_TESTED",
        "infinite_theorem_qualification": "NOT_ASSESSED",
    }


def run_case(case: str) -> dict:
    if case not in CASES:
        raise EvidenceHold("CASE_INVALID")
    train = reference_coefficients(case, TRAIN_MAX)
    learned = fit(train)
    validation = evaluate(case, learned)
    if learned["status"] != "TRAINING_FIT_EXACT":
        raise EvidenceHold("CONTROL_FAILED_TO_FIT")
    if validation["status"] != "FINITE_HOLDOUT_MATCH":
        raise EvidenceHold("CONTROL_FAILED_HELDOUT")
    return {
        "case": case, "training": learned, "evaluation": validation,
        "assessed_scope": "fixed classical identities only, finite coefficients, synthetic mathematics",
    }


def run_experiment() -> dict:
    cases = [run_case(case) for case in sorted(CASES)]
    tampered = list(reference_coefficients("RR1", TRAIN_MAX))
    tampered[6] += 1
    bad_fit = fit(tuple(tampered))
    if bad_fit["status"] != "HOLD_NO_CANDIDATE":
        raise EvidenceHold("TAMPER_NEGATIVE_CONTROL_FAILED")
    base = {
        "schema": SCHEMA,
        "cases": cases,
        "negative_control": {
            "description": "RR1 training n=6 coefficient intentionally increased by one",
            "result": bad_fit["status"],
            "model": None,
        },
        "data_origin": "synthetic exact integer partitions; no archaeological records",
        "dataset_rights": "software-generated mathematical facts",
        "training_type": "CPU exhaustive symbolic parameter fit (not neural weights)",
        "evaluation_type": "separate deterministic finite held-out exact recurrence",
        "source_papers": [
            "https://arxiv.org/abs/2609.20567v2",
            "https://arxiv.org/abs/2607.01544",
        ],
        "historical_khipu_decipherment": False,
        "new_infinite_identity_proved": False,
        "external_Lean_replay_completed": False,
        "independent_scientific_replication": False,
        "signature_verified": False,
        "production_qualification": "NOT_ASSESSED",
        "status": "FINITE_RESEARCH_CONTROL_MATCH",
    }
    return {
        **base, "sha256": hashlib.sha256(DOMAIN + canonical(base)).hexdigest(),
    }


def cli() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write", type=Path, help="exclusively create one reproducible JSON receipt"
    )
    parser.add_argument("--check", type=Path, help="compare a prior receipt byte-for-byte")
    args = parser.parse_args()
    if args.write and args.check:
        parser.error("choose either --write or --check")
    try:
        report = run_experiment()
        data = (json.dumps(report, sort_keys=True, indent=2, ensure_ascii=True) + "\n").encode("ascii")
        if args.check is not None:
            if args.check.is_symlink() or not args.check.is_file() or args.check.read_bytes() != data:
                raise EvidenceHold("RECEIPT_REPRODUCIBILITY_MISMATCH")
        elif args.write is not None:
            if args.write.is_symlink() or not args.write.parent.is_dir():
                raise EvidenceHold("OUTPUT_PATH_INVALID")
            with args.write.open("xb") as handle:
                handle.write(data)
        print(json.dumps({
            "status": report["status"], "sha256": report["sha256"],
            "cases": [
                {
                    "case": row["case"], "model": row["training"]["model"],
                    "hypotheses_tested": row["training"]["candidate_hypotheses_tested"],
                    "candidate_matches": row["training"]["candidate_matches"],
                    "test_matches": row["evaluation"]["exact_matches"],
                    "test_rows": row["evaluation"]["test_rows"],
                }
                for row in report["cases"]
            ],
            "negative_control": report["negative_control"]["result"],
            "receipt_written": bool(args.write),
            "receipt_checked": bool(args.check),
        }, sort_keys=True))
        return 0
    except EvidenceHold as error:
        print(json.dumps({"status": "HOLD", "reason": str(error)}, sort_keys=True))
        return 3


if __name__ == "__main__":
    raise SystemExit(cli())
